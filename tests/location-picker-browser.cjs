const { chromium } = require('playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const runtimeErrors = []
    page.on('pageerror', error => runtimeErrors.push(error.message))
    let posts = 0
    let submitted = ''
    await page.route('https://tile.openstreetmap.org/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#b6d6df"/></svg>' }))
    await page.route('**/api/sightings*', async route => {
      if (route.request().method() === 'POST') {
        posts++
        submitted = route.request().postDataBuffer().toString()
        return route.fulfill({ status: 201, json: { data: { id: 'saved' } } })
      }
      return route.fulfill({ json: { data: [], meta: { localAvailable: true, externalAvailable: true, total: 0, speciesOptions: [], placeOptions: [] } } })
    })
    await page.goto('http://localhost:3000/', { waitUntil: 'domcontentloaded' })
    await page.getByRole('button', { name: 'Report a sighting', exact: true }).click()
    const form = page.locator('[aria-labelledby="report-title"]')
    await form.locator('[name=locationName]').fill('My preserved park')
    await form.locator('[name=observedAt]').fill('2026-01-01')
    await form.locator('[name=region]').selectOption('London')
    await form.locator('[name=notes]').fill('Keep this information')
    await form.locator('[name=photo]').setInputFiles({ name: 'tick.png', mimeType: 'image/png', buffer: Buffer.from('test file preserved without submitting') })
    const lat = form.locator('[name=latitude]'), lng = form.locator('[name=longitude]')
    assert.equal(await lat.getAttribute('required'), null)
    assert.equal(await lng.getAttribute('required'), null)
    await form.getByRole('button', { name: 'Pin location on map', exact: true }).click()
    const emptyPicker = page.getByRole('dialog', { name: 'Pin location on map', exact: true })
    await emptyPicker.getByRole('region', { name: 'Location selection map' }).focus()
    await emptyPicker.locator('.leaflet-tile-loaded').first().waitFor()
    assert.equal(await emptyPicker.getByRole('button', { name: 'Confirm location', exact: true }).isDisabled(), true)
    await page.keyboard.press('Enter')
    await emptyPicker.locator('.location-picker-pin').waitFor()
    const initialCoordinates = (await emptyPicker.locator('dd').allTextContents()).map(Number)
    assert(Math.abs(initialCoordinates[0] - 54.5) < 0.1)
    assert(Math.abs(initialCoordinates[1] + 3) < 0.1)
    await emptyPicker.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await lat.inputValue(), '')
    assert.equal(await lng.inputValue(), '')
    await lat.fill('51.123456')
    await form.getByText('Provide both latitude and longitude, or leave both blank.', { exact: true }).waitFor()
    await form.getByRole('button', { name: 'Submit for review', exact: true }).click()
    assert.equal(posts, 0)
    await lng.fill('-0.987654')
    const opener = form.getByRole('button', { name: 'Edit pinned location', exact: true })
    await opener.focus(); await page.keyboard.press('Enter')
    const picker = page.getByRole('dialog', { name: 'Pin location on map', exact: true })
    await picker.locator('.location-picker-pin').waitFor()
    await picker.getByText('51.123456', { exact: true }).waitFor()
    await picker.getByText('-0.987654', { exact: true }).waitFor()
    const map = picker.getByRole('region', { name: 'Location selection map' })
    await map.click({ position: { x: 150, y: 150 } })
    const first = await picker.locator('[aria-live=polite]').textContent()
    await map.click({ position: { x: 230, y: 180 } })
    const second = await picker.locator('[aria-live=polite]').textContent()
    assert.notEqual(first, second)
    assert.equal(await picker.locator('.location-picker-pin').count(), 1)
    await picker.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await lat.inputValue(), '51.123456')
    assert.equal(await lng.inputValue(), '-0.987654')
    await opener.evaluate(button => { if (document.activeElement !== button) throw Error('Focus not returned to opener') })
    await opener.click()
    await picker.locator('.location-picker-pin').waitFor()
    await picker.getByRole('button', { name: 'Clear pin', exact: true }).click()
    assert.equal(await picker.locator('.location-picker-pin').count(), 0)
    await page.keyboard.press('Escape')
    assert.equal(await lat.inputValue(), '51.123456')
    await opener.click()
    await picker.locator('.location-picker-pin').waitFor()
    await map.focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('Enter')
    assert.equal(await picker.locator('.location-picker-pin').count(), 1)
    await picker.getByRole('button', { name: 'Confirm location', exact: true }).click()
    await form.getByText('Location pinned successfully.', { exact: true }).waitFor()
    assert.notEqual(await lng.inputValue(), '-0.987654')
    assert.equal(posts, 0)
    assert.equal(await form.locator('[name=locationName]').inputValue(), 'My preserved park')
    assert.equal(await form.locator('[name=notes]').inputValue(), 'Keep this information')
    assert.equal(await form.locator('[name=photo]').evaluate(input => input.files[0].name), 'tick.png')
    // Global ranges remain available through the manual alternative and survive reopening.
    await lat.fill('40.7128'); await lng.fill('-74.006')
    await opener.click()
    await picker.getByText('40.712800', { exact: true }).waitFor()
    await picker.getByText('-74.006000', { exact: true }).waitFor()
    await picker.getByRole('button', { name: 'Close location picker', exact: true }).click()
    assert.equal(await lat.inputValue(), '40.7128')
    // Mobile dialog fits the viewport, traps focus, and restores the form on cancel.
    await page.setViewportSize({ width: 390, height: 844 })
    await opener.click()
    await picker.locator('.location-picker-pin').waitFor()
    const box = await picker.boundingBox()
    assert(box.x >= 0 && box.x + box.width <= 390)
    assert(box.y >= 0 && box.y + box.height <= 844)
    await picker.getByRole('button', { name: 'Cancel', exact: true }).focus()
    for (let i = 0; i < 15; i++) {
      await page.keyboard.press('Tab')
      assert(await picker.evaluate(element => element.contains(document.activeElement)), 'Focus stays in picker')
    }
    await page.screenshot({ path: '/tmp/tickwatch-location-picker-mobile.png' })
    await page.keyboard.press('Escape')
    await opener.evaluate(button => { if (document.activeElement !== button) throw Error('Focus not returned after Escape') })
    // Clear is a draft until confirmed; confirming saves the empty pair.
    await opener.click()
    await picker.locator('.location-picker-pin').waitFor()
    await picker.getByRole('button', { name: 'Clear pin', exact: true }).click()
    await picker.getByRole('button', { name: 'Confirm location', exact: true }).click()
    assert.equal(await lat.inputValue(), '')
    assert.equal(await lng.inputValue(), '')
    await form.getByRole('button', { name: 'Pin location on map', exact: true }).waitFor()
    await form.locator('[name=photo]').setInputFiles([])
    await lat.fill('40.7128'); await lng.fill('-74.006')
    await form.getByRole('button', { name: 'Submit for review', exact: true }).click()
    await page.getByText('Report saved successfully', { exact: false }).waitFor()
    assert.equal(posts, 1)
    assert.match(submitted, /name="latitude"\r\n\r\n40.7128/)
    assert.match(submitted, /name="longitude"\r\n\r\n-74.006/)
    assert.deepEqual(runtimeErrors, [])
    console.log('Location picker checks passed: click/move one pin, manual pair validation, confirm/clear/cancel, preserved form/photo, no automatic submission, keyboard focus/Escape/trap, global coordinates and mobile rendering.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
